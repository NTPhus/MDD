r"""Real Qwen dialogue/guard/retry regression with explicitly stubbed audio stages.

Usage: .venv\Scripts\python.exe -u scripts/check_order_conversation_live.py
Exercises the actual LocalSpeechEngine.run method. ASR, phonemes and sentence
completion are fixtures, not model measurements. Every dialogue generation and
retry uses real local base Qwen on CPU. No audio, TTS, network API or training.
"""
from __future__ import annotations

import argparse
import base64
from copy import deepcopy
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import sys
import threading
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))
from scripts import local_chat_process
from scripts.local_speech_engine import LocalSpeechEngine


TRANSCRIPTS = [
    "I would like to order one coffee and one milk tea please",
    "Both iced, please.",
    "Medium, please. Also, I am visiting Da Nang next week.",
]


def questions(text):
    return re.findall(r"[^.!?\n]*\?", text.lower())


def learner_sentence_echo(visible, transcript):
    """Narrow external check for complete clauses, including I'm/I am spelling.

    This is not a semantic paraphrase metric. Questions are excluded so a new
    question about the supplied subject is not confused with a restatement.
    """
    def words(value):
        value = value.lower().replace("’", "'")
        for contraction, expanded in {"i'm": "i am", "we're": "we are", "you're": "you are",
                                      "i've": "i have", "i'll": "i will"}.items():
            value = re.sub(r"\b" + re.escape(contraction) + r"\b", expanded, value)
        return tuple(re.findall(r"[a-z]+", value))
    originals = {words(part) for part in re.split(r"[.!?\n]+", transcript) if len(words(part)) >= 4}
    return any(words(part) in originals for part in re.findall(r"[^.!?\n]+[.!?]?", visible)
               if not part.rstrip().endswith("?"))


def analyzer_fixture(transcript):
    """No waveform is decoded or compared; this is a supplied ASR-text fixture."""
    return {"transcript": transcript, "reference_text": transcript, "reference_source": "asr",
            "reference": None, "comparison": None, "phonemes": [], "missing_words": [],
            "asr_model": "TEST_FIXTURE_NOT_ASR_INFERENCE", "phoneme_model": "TEST_FIXTURE_NO_PHONEMES",
            "audio": {"source": "placeholder_bytes_not_an_audio_recording"},
            "notice": "Test fixture only; no pronunciation measurement was performed."}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "data/generated/order-conversation-qa/pipeline-live.json")
    args = parser.parse_args(argv)
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    report = {
        "started_at": datetime.now(timezone.utc).isoformat(),
        "model": "Qwen3-0.6B", "model_id": "qwen-base", "adapter": None, "device": "cpu",
        "training": False, "paid_api_calls": False, "network_api_calls": False,
        "audio_input_provided": False, "asr_inference": False, "phoneme_inference": False,
        "completion_inference": False, "tts_inference": False,
        "fixtures": {"analyze": "Supplied exact transcript; no acoustic reference or comparison.",
                     "completion": "JSON with unchanged transcript, not generated by Qwen.",
                     "audio_base64": "Placeholder bytes solely to satisfy run's decoded-input parameter."},
        "real_components": ["LocalSpeechEngine.run", "dialogue_request and conversation state",
                            "real Qwen dialogue/retry generations", "streaming echo/semantic guards"],
        "max_real_dialogue_calls_per_turn": 2, "max_real_dialogue_calls_total": 6,
        "model_calls": [], "completion_fixture_calls": [], "turns": [], "checks": [],
        "qualitative_review_required": True,
        "limitations": [
            "This is a text-fixture pipeline regression, not an end-to-end audio or pronunciation test.",
            "Each next turn receives the exact previous emitted assistant text, including a labelled fallback if the pipeline used one.",
            "Sampling is stochastic with no fixed seed; three turns cannot establish reliability.",
            "Meaning checks flag narrow failures; naturalness and the travel turn still require qualitative review.",
        ],
    }

    def save():
        report["elapsed_sec"] = round(time.monotonic() - started, 3)
        output.write_text(json.dumps(report, ensure_ascii=False, indent=2, default=str), encoding="utf-8")

    def check(turn, name, passed, detail):
        report["checks"].append({"turn": turn, "name": name, "passed": bool(passed), "detail": detail})

    class RealDialogueWithFixtureCompletion:
        def __init__(self, number, transcript):
            self.number, self.transcript, self.calls = number, transcript, 0

        def generate(self, request, cancelled, emit):
            if request.get("generation_profile") != "conversation":
                # The only allowed non-dialogue branch is sentence completion.
                # No phoneme reference exists, so coaching must not generate.
                try:
                    payload = json.loads(request["messages"][-1]["content"])
                except (ValueError, TypeError, KeyError):
                    raise RuntimeError("Unexpected non-dialogue request; fixture routing stopped") from None
                if payload.get("transcript") != self.transcript:
                    raise RuntimeError("Unexpected non-dialogue request; not the completion fixture")
                raw = json.dumps({"corrected": self.transcript,
                                  "explanation": "Fixture only: original spoken words are unchanged."})
                metadata = {"finish_reason": "stop", "source": "TEST_FIXTURE_NOT_COMPLETION_INFERENCE"}
                report["completion_fixture_calls"].append({"turn": self.number, "request": deepcopy(request),
                                                            "raw_output": raw, "metadata": metadata})
                emit({"type": "chunk", "text": raw})
                return metadata

            if request.get("model_id") != "qwen-base":
                raise RuntimeError("Dialogue must use base Qwen without a pronunciation adapter")
            if self.calls >= 2 or len(report["model_calls"]) >= 6:
                raise RuntimeError("Real-dialogue generation budget exceeded; no extra model call was made")
            self.calls += 1
            record = {"turn": self.number, "attempt": self.calls, "request": deepcopy(request),
                      "raw_chunks": [], "raw_output": "", "metadata": None}
            report["model_calls"].append(record)
            print(f"Turn {self.number}, real Qwen attempt {self.calls}: starting", flush=True)
            then = time.monotonic()

            def receive(text):
                record["raw_chunks"].append(text)
                record["raw_output"] += text
                emit({"type": "chunk", "text": text})

            try:
                metadata = local_chat_process.complete(request["messages"],
                    {"device": "cpu", "adapter": None, "generation_profile": "conversation"},
                    request["max_tokens"], request["timeout"], on_text=receive, cancelled=cancelled)
                record["metadata"] = deepcopy(metadata)
                return metadata
            except Exception as error:
                record["error"] = {"type": type(error).__name__, "message": str(error)}
                raise
            finally:
                record["elapsed_sec"] = round(time.monotonic() - then, 3)
                save()
                print(f"  Raw: {record['raw_output']!r} ({record['elapsed_sec']}s)", flush=True)

    history = []
    try:
        for number, transcript in enumerate(TRANSCRIPTS, 1):
            engine = object.__new__(LocalSpeechEngine)
            engine.analyze = lambda audio, reference=None, text=transcript: analyzer_fixture(text)
            generated = RealDialogueWithFixtureCompletion(number, transcript)
            events = []
            turn_started = time.monotonic()
            request = {"model_id": "qwen-base", "topic_id": "food", "history": deepcopy(history),
                       "audio_base64": base64.b64encode(b"TEST_FIXTURE_NOT_AUDIO").decode("ascii")}
            metadata = engine.run(request, threading.Event(), lambda value: events.append(deepcopy(value)), generated)
            visible_chunks = [event["text"] for event in events if event.get("type") == "chunk"]
            visible = "".join(visible_chunks).strip()
            speech = next((event["speech"] for event in reversed(events) if event.get("type") == "speech"), {})
            record = {"turn": number, "transcript_fixture": transcript, "actual_history": deepcopy(history),
                      "pipeline_metadata": deepcopy(metadata), "visible_chunks": visible_chunks,
                      "visible_output": visible, "events": events,
                      "elapsed_sec": round(time.monotonic() - turn_started, 3),
                      "real_dialogue_calls": generated.calls,
                      "qualitative_review": {"status": "pending", "observations": "Review the saved visible reply and raw attempts."}}
            report["turns"].append(record)
            check(number, "bounded_real_calls", 1 <= generated.calls <= 2, "At most one production retry is permitted.")
            check(number, "nonempty_visible_reply", bool(visible), "A fallback may be nonempty; inspect reply_source before calling it Qwen success.")
            check(number, "spoken_response_matches_emitted_text", speech.get("spoken_response", "").strip() == visible,
                  "No TTS was called; this compares the text the pipeline would send to voice.")
            check(number, "base_qwen_is_dialogue_model", metadata.get("reply_model_id") == "qwen-base",
                  "No coach adapter is substituted for the conversation model.")
            check(number, "does_not_restate_latest_learner_sentence",
                  not learner_sentence_echo(visible, transcript),
                  "Complete-clause comparison includes common contractions such as I'm/I am; this is not a full semantic paraphrase test.")
            qs = questions(visible)
            if number == 1:
                check(number, "does_not_ask_for_already_provided_order",
                      not any(re.search(r"\bwhat\b[^?]*\b(?:like|want)\b[^?]*\border\b", q) for q in qs),
                      "The user already ordered one coffee and one milk tea.")
                check(number, "asks_meaningful_missing_drink_detail",
                      any(re.search(r"\b(?:hot|iced|cold|temperature|size|small|medium|large)\b", q) for q in qs),
                      "A new missing temperature/size question demonstrates progress beyond the welcome/order loop.")
            elif number == 2:
                check(number, "does_not_ask_already_answered_temperature",
                      not any(re.search(r"\b(?:hot|iced|cold|temperature)\b", q) for q in qs),
                      "Both iced was supplied in the latest utterance.")
                check(number, "asks_missing_size",
                      any(re.search(r"\b(?:size|small|medium|large)\b", q) for q in qs),
                      "A size question is the expected next grounded detail.")
            else:
                check(number, "does_not_return_to_drink_slot_questions",
                      not any(re.search(r"\b(?:order|temperature|size|hot|iced)\b", q) for q in qs),
                      "The user supplied medium and introduced travel; review whether the reply actually follows that topic.")
                record["qualitative_review"]["look_for"] = "Does this follow the Da Nang trip, without inventing a shared meeting or ignoring the most recent topic?"
            history += [{"role": "user", "content": transcript}, {"role": "assistant", "content": visible}]
            print(f"Turn {number}, visible: {visible!r}; source={metadata.get('reply_source', 'qwen')}", flush=True)
            save()
        report["status"] = "completed"
        report["checks_passed"] = all(row["passed"] for row in report["checks"])
    except Exception as error:
        report.update(status="error", checks_passed=False,
                      error={"type": type(error).__name__, "message": str(error)})
        raise
    finally:
        report["finished_at"] = datetime.now(timezone.utc).isoformat()
        save()
        local_chat_process.shutdown()
        print(f"Report: {output}", flush=True)
    print(f"Narrow checks: {'PASS' if report['checks_passed'] else 'FAIL'}; qualitative review is separate.", flush=True)
    return 0 if report["checks_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
